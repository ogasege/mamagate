def card_in(language: str, urgent: bool) -> dict[str, Any]:
    """Return the family card wording for one language."""
    card = CARDS[language]
    return {
        "language": language,
        "name": card["name"],
        "headline": card["urgent"] if urgent else card["soon"],
        "bring_title": card["bring_title"],
        "bring": list(card["bring"]),
        "signs_title": card["signs_title"],
        "signs": list(card["signs"]),
        "speech": VOICES[language][0] is not None,
        "review_note": None if language == "en" else REVIEW_NOTE,
    }


def speech_text(language: str, urgent: bool) -> str:
    """Return the card as one paragraph for text-to-speech (<650 chars)."""
    card = card_in(language, urgent)
    text = (f"{card['headline']} {card['bring_title']}: "
            + ", ".join(card["bring"]) + ". "
            + f"{card['signs_title']}: " + ", ".join(card["signs"]) + ".")
    return text[:640]


def all_cards(urgent: bool) -> list[dict[str, Any]]:
    """Return the card in every supported language."""
    return [card_in(code, urgent) for code in CARDS]
